#!/usr/bin/env tsx
/**
 * shim-surface.ts
 *
 * Enumerates every distinct `Config.<prop>`, `Global.<prop>`,
 * `Global.<method>()`, and `CurrentFile.<prop>` access across src/vendor/**
 * and writes the deduped, file:line-annotated result to docs/shim-surface.md.
 *
 * The shim lanes (src/shims/core-global.ts, src/shims/current-file.ts) use
 * this as their implementation contract — keep it accurate and complete by
 * re-running `npm run shim:surface` whenever src/vendor/** changes.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { Project, SyntaxKind, Node } from 'ts-morph'
import fg from 'fast-glob'

const VENDOR_DIR = 'src/vendor'
const OUT_FILE = 'docs/shim-surface.md'
const TARGETS = ['Config', 'Global', 'CurrentFile'] as const

interface Access {
  target: string
  member: string
  kind: 'property' | 'method'
  file: string
  line: number
  snippet: string
}

function main() {
  const files = fg.sync(`${VENDOR_DIR}/**/*.ts`, { cwd: process.cwd() })
  const project = new Project({ skipAddingFilesFromTsConfig: true })
  for (const f of files)
    project.addSourceFileAtPath(f)

  const accesses: Access[] = []

  for (const sf of project.getSourceFiles()) {
    const filePath = relative(process.cwd(), sf.getFilePath())

    sf.forEachDescendant((node) => {
      if (!Node.isPropertyAccessExpression(node))
        return
      const expr = node.getExpression()
      if (!Node.isIdentifier(expr))
        return
      const target = expr.getText()
      if (!(TARGETS as readonly string[]).includes(target))
        return

      const member = node.getName()
      const parent = node.getParent()
      const isCall = Node.isCallExpression(parent) && parent.getExpression() === node
      const line = sf.getLineAndColumnAtPos(node.getStart()).line

      accesses.push({
        target,
        member,
        kind: isCall ? 'method' : 'property',
        file: filePath,
        line,
        snippet: node.getText(),
      })
    })
  }

  // Dedupe by target+member+kind, keep sorted site list per entry
  type Entry = { target: string, member: string, kind: 'property' | 'method', sites: Set<string> }
  const byKey = new Map<string, Entry>()
  for (const a of accesses) {
    const key = `${a.target}.${a.member}:${a.kind}`
    if (!byKey.has(key))
      byKey.set(key, { target: a.target, member: a.member, kind: a.kind, sites: new Set() })
    byKey.get(key)!.sites.add(`${a.file}:${a.line}`)
  }

  const entries = [...byKey.values()].sort((a, b) =>
    a.target === b.target
      ? a.member.localeCompare(b.member) || a.kind.localeCompare(b.kind)
      : a.target.localeCompare(b.target),
  )

  const lines: string[] = []
  lines.push('# Shim surface')
  lines.push('')
  lines.push('Auto-generated by `scripts/shim-surface.ts` (`npm run shim:surface`). Do not hand-edit.')
  lines.push('')
  lines.push('Every `Config.<x>`, `Global.<x>`, and `CurrentFile.<x>` access found in `src/vendor/**`.')
  lines.push('This is the implementation contract for `src/shims/core-global.ts` and `src/shims/current-file.ts`.')
  lines.push('')

  for (const target of TARGETS) {
    const targetEntries = entries.filter(e => e.target === target)
    lines.push(`## ${target}`)
    lines.push('')
    if (targetEntries.length === 0) {
      lines.push('_(no accesses found)_')
      lines.push('')
      continue
    }
    lines.push('| Member | Kind | Sites |')
    lines.push('| --- | --- | --- |')
    for (const e of targetEntries) {
      const sites = [...e.sites].sort()
      const sitesStr = sites.map(s => `\`${s}\``).join(', ')
      lines.push(`| \`${e.member}\` | ${e.kind === 'method' ? 'method()' : 'property'} | ${sitesStr} |`)
    }
    lines.push('')
  }

  mkdirSync(dirname(OUT_FILE), { recursive: true })
  writeFileSync(OUT_FILE, `${lines.join('\n')}\n`)

  console.log(`[shim-surface] wrote ${OUT_FILE}`)
  for (const target of TARGETS) {
    const count = entries.filter(e => e.target === target).length
    console.log(`[shim-surface] ${target}: ${count} distinct members`)
  }
}

main()
